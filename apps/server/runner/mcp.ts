type JsonRpcId = string | number | null;
export type ToolCaller = (tool: string, args: Record<string, unknown>) => Promise<IpcReply>;
/** The run's tools as the bridge knows them now (protocol 8). */
export type ToolLister = () => Promise<readonly McpToolInfo[]>;

/** How long the MCP process trusts its list before asking again (a `tools/list` within this is answered locally). */
export const TOOLS_CACHE_MS = 30_000;
/** How long the daemon answers an MCP process's list for the same run by itself (`McpBridge`). */
export const LIST_MEMO_MS = TOOLS_CACHE_MS;
/**
 * How often the MCP process asks again in the background while the daemon answers by itself (between a brain
 * process's turns, or the same run's list): a turn's new tools (a grant, a connector, another run's groups) are
 * announced within this of its start. A change notifies the executor.
 */
export const TOOLS_POLL_MS = 1000;
/** …and while each ask reaches the server (a daemon that doesn't answer by itself). */
export const TOOLS_REFRESH_MS = 60_000;

/**
 * The run's tool list in the MCP process (one process per task or run, so
 * the cache is per run). `get` answers from the cache while fresh; `refresh`
 * asks the server (one ask at a time) and says whether the list changed. A
 * failed ask keeps the last list (or, never loaded, the fixed mission tools).
 * Every change it sees, whichever asked, goes to `onChange` (the executor is
 * told to list again): one first seen by a call's `get` was never announced,
 * so a kept-alive Claude Code went on with the list it started with.
 */
export class McpToolCache {
  private list: readonly McpToolInfo[] | null = null;
  private loadedAt = 0;
  private key = "";
  private asking: Promise<boolean> | null = null;
  /** The daemon answered the last ask by itself (between turns, or the same run's list): asking often is free. */
  local = false;

  constructor(
    private readonly fetch: () => Promise<IpcReply>,
    private readonly opts: { ttlMs?: number; now?: () => number; onChange?: () => void } = {},
  ) {}

  get loaded() {
    return this.list !== null;
  }

  async get(): Promise<readonly McpToolInfo[]> {
    const now = (this.opts.now ?? Date.now)();
    if (this.list && now - this.loadedAt < (this.opts.ttlMs ?? TOOLS_CACHE_MS)) return this.list;
    await this.refresh();
    return this.list ?? MISSION_MCP_TOOLS;
  }

  /** Asks the server; true when the list differs from the one before (not on the first load). */
  refresh(): Promise<boolean> {
    this.asking ??= this.ask().finally(() => {
      this.asking = null;
    });
    return this.asking;
  }

  private async ask(): Promise<boolean> {
    const reply = await this.fetch().catch(() => null);
    // A brain process between turns: the next turn is another run, so the list is asked again then.
    const idle = Boolean(reply && !reply.ok && reply.idle);
    this.local = idle || Boolean(reply?.ok && reply.memo);
    if (idle) this.loadedAt = 0;
    if (!reply?.ok || !reply.tools) return false;
    const key = JSON.stringify(reply.tools);
    const changed = this.list !== null && key !== this.key;
    this.list = reply.tools;
    this.key = key;
    this.loadedAt = (this.opts.now ?? Date.now)();
    if (changed) this.opts.onChange?.();
    return changed;
  }
}

const rpcError = (id: JsonRpcId, code: number, message: string) => ({
  jsonrpc: "2.0" as const,
  id,
  error: { code, message },
});

/**
 * One JSON-RPC message from the executor; the response, or null for a
 * notification. Only what an MCP client needs from a tools-only server.
 */
export async function handleMcpMessage(
  message: unknown,
  call: ToolCaller,
  scope?: CommandScope,
  /** Protocol 8: the run's tools from the server (cached); without it, the fixed mission tools. */
  list?: ToolLister,
  /** The turn's permission profile (ADR 0053 §3): a `plan` turn's prompts are answered here, never asked. */
  profile: CommandProfile = "work",
  /** Whose prompts these are: the agent's own branches, and whether a background task asks (`PromptContext`). */
  context: McpContext = {},
): Promise<Record<string, unknown> | null> {
  if (typeof message !== "object" || message === null || Array.isArray(message)) {
    return rpcError(null, -32600, "Invalid request");
  }
  const m = message as { jsonrpc?: unknown; id?: unknown; method?: unknown; params?: unknown };
  const hasId = typeof m.id === "string" || typeof m.id === "number";
  const id: JsonRpcId = hasId ? (m.id as string | number) : null;
  if (m.jsonrpc !== "2.0" || typeof m.method !== "string")
    return hasId ? rpcError(id, -32600, "Invalid request") : null;
  const params = (typeof m.params === "object" && m.params !== null ? m.params : {}) as Record<string, unknown>;
  const { delegated } = context;
  if (m.method === "notifications/cancelled" && delegated) {
    const asked = params.requestId;
    if (typeof asked === "string" || typeof asked === "number") delegated.cancel(asked);
  }
  // Notifications (`notifications/initialized`, `notifications/cancelled`…) need no answer.
  if (!hasId) return null;
  switch (m.method) {
    case "initialize":
      return {
        jsonrpc: "2.0",
        id,
        result: {
          protocolVersion: typeof params.protocolVersion === "string" ? params.protocolVersion : MCP_PROTOCOL_VERSION,
          capabilities: { tools: { listChanged: Boolean(list) } },
          serverInfo: { name: "agentes", version: RUNNER_VERSION },
          instructions: context.local
            ? delegated
              ? "Claude Code's tools, on this computer. There are no tools of agentes.chat to call here."
              : "Only the permission prompt Claude Code asks by itself: there are no tools of agentes.chat to call here."
            : list
              ? "Tools of agentes.chat for this agent: its connectors, context, Drive and, in a mission, the mission tools (keep the plan with update_plan, report milestones, ask decisions with ask_decision, ask approval before any merge, deploy or rollback). When a tool says to stop and wait, end your turn."
              : "Tools of agentes.chat for this mission: keep the plan with update_plan, report milestones, ask decisions with ask_decision, ask for a review when you have something to show, and ask approval before any merge, deploy or rollback.",
        },
      };
    case "ping":
      return { jsonrpc: "2.0", id, result: {} };
    case "tools/list":
      return {
        jsonrpc: "2.0",
        id,
        result: {
          // Read-only tools say so (Codex runs them without an approval even when told to ask).
          tools: [
            ...(delegated?.tools ?? []),
            ...(list ? await list() : MISSION_MCP_TOOLS)
              .filter((tool) => !delegated?.tools.some((t) => t.name === tool.name))
              .map((tool) => ({
                ...tool,
                ...(READ_ONLY_TOOLS.has(tool.name) ? { annotations: { readOnlyHint: true } } : {}),
                ...(ALWAYS_LOADED.has(tool.name) ? { _meta: { "anthropic/alwaysLoad": true } } : {}),
              })),
          ],
        },
      };
    case "tools/call": {
      const name = typeof params.name === "string" ? params.name : "";
      if (delegated?.tools.some((t) => t.name === name)) {
        const given = params.arguments;
        const input = typeof given === "object" && given !== null && !Array.isArray(given) ? given : {};
        const result = await delegated.call(name, input as Record<string, unknown>, {
          id: id as string | number,
          ask: call,
        });
        return { jsonrpc: "2.0", id, result };
      }
      const tools = list ? await list() : MISSION_MCP_TOOLS;
      // With the server's list, a name it lacks still goes there: the executor may list what it had before (a
      // kept-alive one), and the server runs any tool the agent may use, or says why not and what to call instead.
      const served = Boolean(list) && !context.local;
      if (!served && !tools.some((t) => t.name === name)) return rpcError(id, -32602, `Unknown tool: ${name}`);
      const args =
        typeof params.arguments === "object" && params.arguments !== null && !Array.isArray(params.arguments)
          ? (params.arguments as Record<string, unknown>)
          : {};
      // Claude Code's permission prompt: always an answer it understands (allow or deny JSON), never an error.
      if (name === PERMISSION_TOOL) {
        const answer = await permissionPrompt(args, call, { ...(scope ? { scope } : {}), profile, ...context });
        return { jsonrpc: "2.0", id, result: { content: [{ type: "text", text: JSON.stringify(answer) }] } };
      }
      const reply = await call(name, args);
      return {
        jsonrpc: "2.0",
        id,
        result: {
          content: [{ type: "text", text: reply.ok ? reply.text : reply.error }],
          isError: !reply.ok,
        },
      };
    }
    default:
      return rpcError(id, -32601, `Method not found: ${m.method}`);
  }
}

/** What Claude Code's `--permission-prompt-tool` must answer. */
export type PermissionAnswer =
  | { behavior: "allow"; updatedInput: Record<string, unknown> }
  | { behavior: "deny"; message: string };

/** Whose prompts the tool answers, besides where they run (`AGENTES_MCP_BRANCHES`, `AGENTES_MCP_TASK`). */
export interface PromptContext {
  /** The agent's own branch prefixes (`agentes/<handle>/`, a mission's): a push there needs nobody. */
  branches?: readonly string[];
  /** A background task's executor asks: nobody can approve anything from inside it. */
  task?: boolean;
  /** Nobody answers beyond this computer (a background task outside a mission): an ordinary push goes through here. */
  local?: boolean;
  /**
   * How much the agent asks, when it isn't the default (`BrainTurnRequest.permissions.asks`). `always`: nothing but a
   * read is decided here, a push to its own branches included. `never`: a held command is refused with where it
   * runs (`unaskedMessage`).
   */
  asks?: "always" | "never";
}

/** What an MCP process serves besides the server's tools. */
type McpContext = PromptContext & { delegated?: DelegatedSurface };

/**
 * Claude Code asks (`--permission-prompt-tool mcp__agentes__permission_prompt`)
 * when a command isn't on the task's allow list (every push does: `ask`), and
 * the runner asks the same for each of Codex's command and file approvals (ADR
 * 0053 §3): one decision for both. First what the computer decides by itself
 * (`localVerdict`): deny-list commands and secrets are refused at once (never
 * shown to anyone); plain reads (`ls` of any folder, read-only git, a GET with
 * curl in a work turn) are allowed at once, with no card and nothing posted;
 * in a `plan` turn everything else is refused. Then pushes, read with git
 * (`commandApproval`): one that waits for a person is refused here with why
 * and how to ask (or, through our git proxy, where to go instead); one alone
 * to the agent's own branches, or to another branch through the proxy, goes
 * through. The
 * rest goes to the server, which allows it by a mission rule or code's rules
 * for a run, or posts the command card in the thread. Then we ask the server
 * every `pollMs` (short calls; no request stays open) until someone answers
 * or `waitMs` passes: then it is denied.
 */
export async function permissionPrompt(
  args: Record<string, unknown>,
  call: ToolCaller,
  opts: PromptContext & {
    waitMs?: number;
    pollMs?: number;
    sleep?: (ms: number) => Promise<void>;
    now?: () => number;
    /** Where the task runs: plain reads are allowed here without asking. */
    scope?: CommandScope;
    /** The turn's permission profile (default `work`). */
    profile?: CommandProfile;
  } = {},
): Promise<PermissionAnswer> {
  const toolName = typeof args.tool_name === "string" ? args.tool_name : "";
  const input =
    typeof args.input === "object" && args.input !== null && !Array.isArray(args.input)
      ? (args.input as Record<string, unknown>)
      : {};
  if (!toolName) return { behavior: "deny", message: "Unknown tool." };
  const how = opts.task ? ASK_AFTER_TASK : ASK_IN_CHAT;
  const verdict = localVerdict(toolName, input, opts.scope, opts.profile ?? "work", how);
  // A background task's executor has no run_code to be pointed to: it keeps "stop and say so".
  const said = (message: string) => (opts.asks === "never" && !opts.task ? unaskedMessage(message) : message);
  if (verdict?.behavior === "deny") return { behavior: "deny", message: said(verdict.message) };
  if (verdict?.behavior === "allow") return { behavior: "allow", updatedInput: input };
  if (toolName === "Bash" && typeof input.command === "string") {
    const own = opts.branches ?? [];
    const cwd = opts.scope?.cwd ?? null;
    const held = await commandApproval(input.command, { cwd, own, how, script: true });
    if (held) return { behavior: "deny", message: held.never ? held.message : said(held.message) };
    // A push alone to its own branches, or through our git proxy (which decides someone else's branch with a
    // person's grant, so no card here asks first). An agent that always asks is asked for these too.
    const push = lonePush(input.command);
    const alone = opts.local || opts.asks !== "always";
    if (push && alone && (opts.local || pushesOwnBranches(push, own) || (await pushThroughProxy(push, cwd)))) {
      return { behavior: "allow", updatedInput: input };
    }
  }
  const now = opts.now ?? Date.now;
  const sleep = opts.sleep ?? ((ms: number) => new Promise<void>((r) => setTimeout(r, ms)));
  const deadline = now() + (opts.waitMs ?? PERMISSION_WAIT_MS);
  const ask = async (a: Record<string, unknown>) => {
    let reply = await call(PERMISSION_TOOL, a);
    // The runner restarting or reconnecting: keep asking (within the wait), never a silent deny.
    while (!reply.ok && reply.transient && now() < deadline) {
      await sleep(opts.pollMs ?? PERMISSION_POLL_MS);
      reply = await call(PERMISSION_TOOL, a);
    }
    if (!reply.ok) return { error: reply.error };
    try {
      return JSON.parse(reply.text) as { behavior?: string; message?: string; status?: string; request_id?: string };
    } catch {
      return { error: "agentes.chat answered something unexpected." };
    }
  };
  let out = await ask({
    tool_name: toolName.slice(0, 64),
    input,
    ...(typeof args.tool_use_id === "string" ? { tool_use_id: args.tool_use_id.slice(0, 128) } : {}),
    ...(opts.scope ? { scope: opts.scope } : {}),
  });
  const requestId = "request_id" in out && typeof out.request_id === "string" ? out.request_id : "";
  for (;;) {
    if ("error" in out && out.error) return { behavior: "deny", message: `Not allowed: ${out.error}` };
    if ("behavior" in out && out.behavior === "allow") return { behavior: "allow", updatedInput: input };
    if ("behavior" in out && out.behavior === "deny") {
      return { behavior: "deny", message: String(out.message ?? "A person said no.").slice(0, 500) };
    }
    if (!requestId || now() >= deadline) return { behavior: "deny", message: PERMISSION_TIMEOUT_MESSAGE };
    await sleep(opts.pollMs ?? PERMISSION_POLL_MS);
    out = await ask({ request_id: requestId });
  }
}

/**
 * `agentes-runner mcp --task <id>`: serves MCP on stdin/stdout until stdin
 * closes. Nothing else may be written to stdout (it is the protocol).
 */
export async function runMcpServer(options: {
  taskId: string;
  socketPath: string;
  /** From the env the executor got; else the task folder's token file. */
  token: string | null;
  tokenFile?: string;
  input?: NodeJS.ReadableStream;
  output?: NodeJS.WritableStream;
  scope?: CommandScope;
  /** The turn's permission profile (default: `AGENTES_MCP_PROFILE`, else `work`). */
  profile?: CommandProfile;
  refreshMs?: number;
  /** Tests: `TOOLS_POLL_MS`. */
  pollMs?: number;
  /** How calls reach the daemon. Default: over `socketPath`. Inside the daemon (a `session`): straight to its bridge. */
  ipc?: (req: IpcRequest) => Promise<IpcReply>;
  /** Default: `AGENTES_MCP_BRANCHES` and `AGENTES_MCP_TASK`. */
  context?: McpContext;
}): Promise<number> {
  const token =
    options.token ??
    (() => {
      try {
        return options.tokenFile ? readFileSync(options.tokenFile, "utf8").trim() : "";
      } catch {
        return "";
      }
    })();
  const out = options.output ?? process.stdout;
  const write = (msg: unknown) => out.write(`${JSON.stringify(msg)}\n`);
  const context: McpContext = options.context ?? mcpContextFromEnv(process.env);
  const ipc = options.ipc ?? ((req: IpcRequest) => ipcCall(options.socketPath, req));
  // A background task outside a mission has no tools of ours: only the prompt, answered on this computer.
  const call: ToolCaller = context.local
    ? async () => ({ ok: false, error: NOBODY_TO_ASK })
    : (tool, args) => ipc({ taskId: options.taskId, token, tool, args });
  // The run's tools, asked from the server through the daemon (cached here: one process per task or run). A list
  // that changed (a scope granted, a connector added, a mission thread, another run's groups): the executor re-reads
  // it (Claude Code 2.1.316 does, between the tool calls of a turn; Codex 0.165.0 doesn't, `brain-codex-app.ts`).
  const cache = new McpToolCache(() => ipc({ taskId: options.taskId, token, tool: "", args: {}, kind: "list" }), {
    onChange: () => write({ jsonrpc: "2.0", method: "notifications/tools/list_changed" }),
  });
  const list: ToolLister = context.local ? async () => PROMPT_ONLY : () => cache.get();
  let stopped = false;
  let refresher: ReturnType<typeof setTimeout> | undefined;
  const refreshLater = () => {
    if (stopped) return;
    // Before the executor's first list there is nothing to ask about: looked at again soon, for free.
    const often = !cache.loaded || cache.local;
    const ms = often ? (options.pollMs ?? TOOLS_POLL_MS) : (options.refreshMs ?? TOOLS_REFRESH_MS);
    refresher = setTimeout(() => {
      if (!cache.loaded) refreshLater();
      else void cache.refresh().finally(refreshLater);
    }, ms);
    refresher.unref?.();
  };
  refreshLater();
  const scope = options.scope ?? mcpScopeFromEnv(process.env);
  const profile = options.profile ?? mcpProfileFromEnv(process.env);
  const rl = createInterface({ input: options.input ?? process.stdin, crlfDelay: Number.POSITIVE_INFINITY });
  const inflight = new Set<Promise<void>>();
  for await (const line of rl) {
    if (!line.trim()) continue;
    let message: unknown;
    try {
      message = JSON.parse(line);
    } catch {
      write(rpcError(null, -32700, "Parse error"));
      continue;
    }
    const p = handleMcpMessage(message, call, scope, list, profile, context)
      .then((res) => {
        if (res) write(res);
      })
      .catch(() => undefined)
      .finally(() => inflight.delete(p));
    inflight.add(p);
  }
  // The CLI is gone: nobody takes these calls' answers. What was moved to the background stays.
  context.delegated?.cancel();
  await Promise.all(inflight);
  stopped = true;
  clearTimeout(refresher);
  return 0;
}

/**
 * `agentes-runner mcp --relay`: a delegated CLI's MCP server, as seen from the user holding the sign-in. It says who
 * it is, then only moves bytes: nothing the model or the agent's code wrote is read in that user's process.
 */
export function runMcpRelay(options: {
  taskId: string;
  socketPath: string;
  token: string;
  input?: NodeJS.ReadableStream;
  output?: NodeJS.WritableStream;
}): Promise<number> {
  return new Promise((resolve) => {
    const socket = createConnection(options.socketPath);
    socket.once("error", () => resolve(1));
    socket.once("close", () => resolve(0));
    socket.once("connect", () => {
      const hello: IpcRequest = { kind: "session", taskId: options.taskId, token: options.token, tool: "", args: {} };
      socket.write(`${JSON.stringify(hello)}\n`);
      (options.input ?? process.stdin).pipe(socket);
      socket.pipe(options.output ?? process.stdout);
    });
  });
}

