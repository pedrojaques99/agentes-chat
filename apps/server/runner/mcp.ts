/**
 * The local `agentes` MCP server of a mission task (protocol 5, ADR 0029).
 *
 * - `agentes-runner mcp --task <taskId>` is a stdio MCP server the executor
 *   (Claude Code, Codex) starts from its MCP config. It speaks the minimal
 *   MCP JSON-RPC (`initialize`, `tools/list`, `tools/call`, `ping`), one JSON
 *   message per line, and forwards each tool call to the runner daemon.
 * - The daemon (`agentes-runner start`) listens on a local endpoint in the
 *   runner home (a unix socket; a named pipe on Windows). Each request carries
 *   the task id and the task's random token, generated by the daemon when it
 *   started the task (in the executor's MCP config env, and in the task's
 *   folder, mode 600). Only a running mission task with the right token gets
 *   through; the daemon relays it to the server as `mcp.call` and the
 *   server's `mcp.result` comes back the same way.
 * - The server decides everything (the task must be this machine's and the
 *   mission's); the runner only checks the token.
 * - Protocol 8 (ADR 0032): a bridge with no tools of its own. The server
 *   gives the task (or a computer-brain run) its own token; the daemon sends
 *   it with every call, `tools/list` is asked from the server (cached per
 *   run in the MCP process, refreshed in the background: a change tells the
 *   executor `notifications/tools/list_changed`), and any tool name goes to
 *   the server, which decides. Without a server token: the fixed mission tools.
 */

/** Daemon side: what a task needs to call through the bridge. */
export interface McpTaskInfo {
  token: string;
  missionId: string;
  running: boolean;
  /** Where the task runs (absolute) and its agent's folder (absolute): paths the executor gives are resolved here. */
  cwd?: string;
  folder?: string;
  /** The agent's secrets masked (ADR 0027): nothing the executor sends leaves the machine with them. */
  redact?: (text: string) => string;
  /**
   * Protocol 8: the server's token for this task's (or run's) tools (ADR
   * 0032). With it the bridge relays any tool and asks the server for the list.
   */
  serverToken?: string;
  /**
   * Brain turns (protocol 8, ADR 0032): the MCP server belongs to a Claude Code
   * process that lives across turns; its calls are relayed for the run it works
   * for now (`mcp.call.taskId` = this run id), with that run's `serverToken`
   * from `brain.turn`.
   */
  runId?: string;
  /**
   * A brain process between turns: alive, but no run is thinking, so nothing
   * is relayed. Its MCP server's background list refresh is answered quietly
   * (no ended run's token is ever sent, nothing is logged).
   */
  idle?: boolean;
  /**
   * A CLI with the delegated profile: Claude Code's own tools, served here (`delegated-tools.ts`). Its relay opens a
   * `session`, the only way to them; every other executor's list and calls stay as they are.
   */
  delegated?: DelegatedSurface;
}

/** One block of a tool's result (MCP `content`). */
export type McpContent = { type: "text"; text: string } | { type: "image"; data: string; mimeType: string };
export type McpToolResult = { content: McpContent[]; isError: boolean };

/** What `delegated-tools.ts` serves on a session. */
export interface DelegatedSurface {
  tools: readonly McpToolInfo[];
  scope: CommandScope;
  profile: CommandProfile;
  branches?: readonly string[];
  /** `PromptContext`'s. */
  asks?: "always" | "never";
  task?: boolean;
  local?: boolean;
  /** `id`: the JSON-RPC request's, for `cancel`. `ask`: the bridge, for the permission prompt. */
  call(
    name: string,
    args: Record<string, unknown>,
    ctx: { id: string | number; ask: ToolCaller },
  ): Promise<McpToolResult>;
  /** Ends the call `id`, or without it every call in progress. */
  cancel(id?: string | number): void;
}

/** Every string inside `value` through `redact` (keys kept). */
export function redactDeep(value: unknown, redact: (text: string) => string): unknown {
  if (typeof value === "string") return redact(value);
  if (Array.isArray(value)) return value.map((v) => redactDeep(v, redact));
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value as Record<string, unknown>).map(([k, v]) => [k, redactDeep(v, redact)]),
    );
  }
  return value;
}

/** Paths in the agent's folder but outside the task's own folder travel with this prefix (the server resolves it). */
export const FOLDER_PATH_PREFIX = "@folder/";

/**
 * A path the executor gave (`upload_artifact`, `request_review`), as the
 * server expects it: relative to the task's folder; an absolute one inside
 * the task's folder becomes relative, one elsewhere in the agent's folder
 * gets `@folder/`, anything outside is refused (null).
 */
export function resolveTaskPath(given: string, info: Pick<McpTaskInfo, "cwd" | "folder">): string | null {
  const p = given.trim();
  if (!p) return p;
  const absolute = path.isAbsolute(p) || /^[a-zA-Z]:[\\/]/.test(p);
  if (!absolute) return p;
  const abs = path.resolve(p);
  const inside = (root: string | undefined) => {
    if (!root) return null;
    const rel = path.relative(root, abs);
    return rel === "" || (!rel.startsWith("..") && !path.isAbsolute(rel)) ? rel.split(path.sep).join("/") : null;
  };
  const inCwd = inside(info.cwd);
  if (inCwd !== null) return inCwd || ".";
  const inFolder = inside(info.folder);
  if (inFolder !== null) return `${FOLDER_PATH_PREFIX}${inFolder}`;
  return null;
}

const PATH_ARGS: Record<string, "path" | "paths"> = {
  upload_artifact: "path",
  request_review: "paths",
  complete_mission: "paths",
};

export interface IpcRequest {
  taskId: string;
  token: string;
  tool: string;
  args: Record<string, unknown>;
  /**
   * `list`: the tools this task (or run) may use (`tool` and `args` unused). `session`: a delegated CLI's relay (the
   * rest of the connection is MCP itself, `runMcpRelay`). Default: a call.
   */
  kind?: "call" | "list" | "session";
}

/**
 * `transient`: the link to the runner or to agentes.chat was down; asking again later may work. `tools`: a list's
 * answer. `memo`: a list the daemon answers again by itself for the same run (`LIST_MEMO_MS`), so asking often is free.
 */
export type IpcReply =
  | { ok: true; text: string; tools?: McpToolInfo[]; memo?: boolean }
  | { ok: false; error: string; transient?: boolean; idle?: boolean };

/** What a tool name may look like (the Tool Gateway's rule). */
const TOOL_NAME = /^[a-zA-Z0-9_-]{1,64}$/;

/** The pseudo tool name of a list request (in pending and resend bookkeeping). */
const LIST = "tools/list";

/** A listed tool as the server sent it (anything else is dropped). */
function isToolInfo(v: unknown): v is McpToolInfo {
  if (typeof v !== "object" || v === null) return false;
  const t = v as Record<string, unknown>;
  return (
    typeof t.name === "string" &&
    TOOL_NAME.test(t.name) &&
    typeof t.description === "string" &&
    typeof t.inputSchema === "object" &&
    t.inputSchema !== null &&
    !Array.isArray(t.inputSchema)
  );
}

/** Unix socket paths longer than this don't fit `sun_path` (104 bytes on macOS, 108 on Linux). */
const MAX_SOCKET_PATH = 100;

/**
 * Where the daemon listens: `<runner home>/mcp.sock`, or a named pipe on
 * Windows. A home whose path is too long for a unix socket (the desktop
 * app's `~/.agentes-runner/orgs/<id>/` with a long user name) gets one in
 * the temp folder, named after the home.
 */
export function mcpSocketPath(home: string, platform: NodeJS.Platform = process.platform, tmp = os.tmpdir()) {
  const id = createHash("sha256").update(home).digest("hex").slice(0, 16);
  if (platform === "win32") return `\\\\.\\pipe\\agentes-runner-${id}`;
  const inHome = path.join(home, "mcp.sock");
  if (Buffer.byteLength(inHome) <= MAX_SOCKET_PATH) return inHome;
  return path.join(tmp, `agentes-runner-${id}.sock`);
}

export const newMcpToken = () => randomBytes(24).toString("base64url");

/** The token file in a task's folder (the MCP process reads it when its env has none). */
export const MCP_TOKEN_FILE = "mcp-token";

const sameToken = (a: string, b: string) => {
  const x = Buffer.from(a);
  const y = Buffer.from(b);
  return x.length === y.length && timingSafeEqual(x, y);
};

/** Calls the bridge may send again after a reconnect (the server answers them the same way twice). */
const RESEND_SAFE = new Set<string>([PERMISSION_TOOL, "get_context", LIST]);

/** How long a relayed call may take (an upload of a large file takes minutes). */
export const MCP_CALL_TIMEOUT_MS = 6 * 60_000;

/** A call sent before the connection dropped whose answer never came: the server may have run it, in part. */
export const MCP_CUT_OFF =
  "The connection to agentes.chat dropped while this ran and no answer came: it may have run in part. Check before doing it again.";

/**
 * The daemon's half: a local endpoint for the MCP processes of this
 * machine's mission tasks, relaying their calls to the server.
 */
export class McpBridge {
  private server: Server | null = null;
  private relays: { path: string; server: Server } | null = null;
  /** The relays' connections, which stay open: closing a server waits for them. */
  private readonly sessions = new Set<Socket>();
  private send: ((frame: RunnerFrame) => void) | null = null;
  private readonly pending = new Map<
    string,
    {
      resolve: (r: IpcReply) => void;
      timer: ReturnType<typeof setTimeout>;
      frame: RunnerFrame;
      tool: string;
      /** Sent again under the same `callId` after a reconnect (`detach`). */
      resend: boolean;
      /** It reached a connection once. */
      sent?: boolean;
      /** A connection dropped after it was sent: the server may have run it. */
      cut?: boolean;
    }
  >();
  /** Calls made while the connection is down (a restart, a reconnect): relayed once it is back. */
  private readonly waiting = new Map<string, { frame: RunnerFrame; tool: string }>();
  /** The list each MCP process got last (by its task or process id), for the run it was for. */
  private readonly lists = new Map<string, { run: string; at: number; reply: IpcReply }>();

  constructor(
    private readonly opts: {
      socketPath: string;
      /** The task's MCP token and state (from the task journal). */
      task: (taskId: string) => McpTaskInfo | null;
      log?: (line: string) => void;
      callTimeoutMs?: number;
    },
  ) {}

  get socketPath() {
    return this.opts.socketPath;
  }

  /** Starts listening (a stale socket file from a previous runner is removed first). */
  async listen() {
    if (this.server) return;
    this.server = await this.open(this.opts.socketPath);
  }

  /**
   * A delegated CLI's way in: its relay runs as the sign-in's user, who can't reach `socketPath`. The socket is open to
   * anyone who can enter its folder, so root sets access on that folder alone: root never touches a path in it, which
   * the agent could swap for a link.
   */
  async listenForRelays(socketPath: string) {
    if (this.relays?.path === socketPath) return;
    await this.closeRelays();
    this.relays = { path: socketPath, server: await this.open(socketPath) };
    chmodSync(socketPath, 0o666);
  }

  private async closeRelays() {
    const relays = this.relays;
    this.relays = null;
    for (const socket of this.sessions) socket.destroy();
    if (!relays) return;
    await new Promise<void>((resolve) => relays.server.close(() => resolve()));
    rmSync(relays.path, { force: true });
  }

  private async open(socketPath: string) {
    if (process.platform !== "win32" && existsSync(socketPath)) rmSync(socketPath, { force: true });
    const server = createServer((socket) => this.serve(socket));
    const events = server as unknown as EventEmitter;
    await new Promise<void>((resolve, reject) => {
      events.once("error", reject);
      server.listen(socketPath, () => {
        events.off("error", reject);
        resolve();
      });
    });
    events.on("error", (err: Error) => this.opts.log?.(`mcp endpoint: ${err.message}`));
    return server;
  }

  /**
   * A connection to the server is up: calls go there, the ones that waited first. One sent before a drop goes
   * again only to a server that runs a call once per `callId` (its `welcome`): an older one would run it twice.
   */
  attach(send: (frame: RunnerFrame) => void, server: { mcpOnce?: boolean } = {}) {
    this.send = send;
    for (const [callId, w] of this.waiting) {
      this.waiting.delete(callId);
      const p = this.pending.get(callId);
      if (p?.cut && !RESEND_SAFE.has(p.tool) && !server.mcpOnce) {
        clearTimeout(p.timer);
        this.pending.delete(callId);
        p.resolve({ ok: false, error: MCP_CUT_OFF });
        continue;
      }
      this.relay(callId, w.frame);
    }
  }

  /**
   * The connection went away. Calls not answered yet wait for the connection
   * and go again under the same `callId` (a server that runs a call once per
   * id answers a repeat with the first answer), when that is safe: a mission
   * task's calls (its executor runs on through a drop), the permission prompt
   * (keyed by its request) and reads. A brain turn's other calls fail as
   * transient: the turn itself was cut, and it is sent again whole.
   */
  detach() {
    this.send = null;
    for (const [callId, p] of this.pending) {
      if (p.resend) {
        if (p.sent) p.cut = true;
        this.waiting.set(callId, { frame: p.frame, tool: p.tool });
        continue;
      }
      clearTimeout(p.timer);
      p.resolve({
        ok: false,
        error: "The computer lost its connection to agentes.chat. Try again in a minute.",
        transient: true,
      });
      this.pending.delete(callId);
    }
  }

  private relay(callId: string, frame: RunnerFrame) {
    const p = this.pending.get(callId);
    const send = this.send;
    if (!p) return;
    if (!send) {
      this.waiting.set(callId, { frame, tool: p.tool });
      return;
    }
    try {
      send(frame);
      p.sent = true;
    } catch {
      // The socket broke while sending: wait for the next connection.
      this.waiting.set(callId, { frame, tool: p.tool });
    }
  }

  /** The server's answer to a call. */
  result(frame: Extract<ServerFrame, { type: "mcp.result" }>) {
    const p = this.pending.get(frame.callId);
    if (!p) return;
    clearTimeout(p.timer);
    this.pending.delete(frame.callId);
    p.resolve(frame.ok ? { ok: true, text: String(frame.text ?? "") } : { ok: false, error: frame.error.message });
  }

  /** The server's answer to a list (protocol 8). */
  tools(frame: Extract<ServerFrame, { type: "mcp.tools" }>) {
    const p = this.pending.get(frame.callId);
    if (!p) return;
    clearTimeout(p.timer);
    this.pending.delete(frame.callId);
    p.resolve(
      frame.ok
        ? { ok: true, text: "", tools: (Array.isArray(frame.tools) ? frame.tools : []).filter(isToolInfo) }
        : { ok: false, error: frame.error.message },
    );
  }

  /** One call from an MCP process: token checked, relayed, answered. */
  async handle(req: IpcRequest): Promise<IpcReply> {
    const taskId = typeof req.taskId === "string" ? req.taskId : "";
    const info = taskId ? this.opts.task(taskId) : null;
    if (!info || typeof req.token !== "string" || !sameToken(info.token, req.token)) {
      return { ok: false, error: "Not allowed: this task has no agentes tools." };
    }
    if (!info.running) {
      // A brain process between turns: its background refresh waits for the next turn, quietly.
      if (info.idle)
        return { ok: false, error: "No turn is running right now. Try again in your next turn.", idle: true };
      return { ok: false, error: "This task has ended." };
    }
    if (req.kind === "list") {
      // An older server gave no token: the fixed mission tools.
      if (!info.serverToken) return { ok: true, text: "", tools: [...MISSION_MCP_TOOLS] };
      // Each MCP process asks every second: the same run's list is answered here, the server asked for a new run
      // (a brain process's next turn) or once the last answer is `LIST_MEMO_MS` old.
      const run = `${info.runId ?? taskId}:${info.serverToken}`;
      const now = Date.now();
      const last = this.lists.get(taskId);
      if (last && last.run === run && now - last.at < LIST_MEMO_MS) return last.reply;
      const callId = randomBytes(12).toString("hex");
      const reply = await this.relayAndWait(
        callId,
        LIST,
        { type: "mcp.list", callId, taskId: info.runId ?? taskId, token: info.serverToken },
        true,
      );
      if (!reply.ok) return reply;
      for (const [id, l] of this.lists) if (now - l.at >= LIST_MEMO_MS) this.lists.delete(id);
      const kept: IpcReply = { ...reply, memo: true };
      this.lists.set(taskId, { run, at: now, reply: kept });
      return kept;
    }
    const tool = typeof req.tool === "string" ? req.tool.slice(0, 64) : "";
    // A bridge (server token): any tool the server lists; the server decides. Else the fixed mission tools.
    const known = info.serverToken ? TOOL_NAME.test(tool) : MISSION_MCP_TOOLS.some((t) => t.name === tool);
    if (!known) return { ok: false, error: `Unknown tool ${tool}` };
    const given = req.args && typeof req.args === "object" && !Array.isArray(req.args) ? req.args : {};
    if (JSON.stringify(given).length > MCP_ARGS_MAX_CHARS) {
      return {
        ok: false,
        error: `The arguments are too large (more than ${MCP_ARGS_MAX_CHARS / (1024 * 1024)} MB). Keep big content in a file in your folder: to change a repository, commit and push it with git.`,
      };
    }
    // Secrets never leave the machine through our tools (the server masks again).
    const args = (info.redact ? redactDeep(given, info.redact) : given) as Record<string, unknown>;
    const pathArg = PATH_ARGS[tool];
    if (pathArg === "path" && typeof args.path === "string") {
      const resolved = resolveTaskPath(args.path, info);
      if (resolved === null)
        return { ok: false, error: `${args.path} is outside your folder: copy it into your folder first.` };
      args.path = resolved;
    } else if (pathArg === "paths" && Array.isArray(args.paths)) {
      const out: string[] = [];
      for (const p of args.paths) {
        const resolved = typeof p === "string" ? resolveTaskPath(p, info) : null;
        if (resolved === null)
          return { ok: false, error: `${String(p)} is outside your folder: copy it into your folder first.` };
        out.push(resolved);
      }
      args.paths = out;
    }
    // Not connected right now (the runner restarting, a reconnect): the call waits for the
    // connection, bounded by its own timeout, instead of being refused.
    const callId = randomBytes(12).toString("hex");
    const frame: RunnerFrame = {
      type: "mcp.call",
      callId,
      taskId: info.runId ?? taskId,
      tool,
      args,
      ...(info.serverToken ? { token: info.serverToken } : {}),
    };
    return this.relayAndWait(callId, tool, frame, !info.runId || RESEND_SAFE.has(tool));
  }

  private relayAndWait(callId: string, tool: string, frame: RunnerFrame, resend: boolean) {
    return new Promise<IpcReply>((resolve) => {
      const timer = setTimeout(() => {
        const cut = this.pending.get(callId)?.cut === true && !RESEND_SAFE.has(tool);
        const waited = this.waiting.has(callId);
        this.pending.delete(callId);
        this.waiting.delete(callId);
        resolve(
          cut
            ? { ok: false, error: MCP_CUT_OFF }
            : waited
              ? {
                  ok: false,
                  error: "The computer is not connected to agentes.chat right now. Try again in a minute.",
                  transient: true,
                }
              : { ok: false, error: "agentes.chat did not answer in time." },
        );
      }, this.opts.callTimeoutMs ?? MCP_CALL_TIMEOUT_MS);
      timer.unref?.();
      this.pending.set(callId, { resolve, timer, frame, tool, resend });
      this.relay(callId, frame);
    });
  }

  private serve(socket: Socket) {
    let buf = "";
    socket.setEncoding("utf8");
    socket.on("error", () => {});
    const onData = (chunk: string) => {
      buf += chunk;
      if (buf.length > MCP_ARGS_MAX_CHARS * 2) {
        socket.end(`${JSON.stringify({ ok: false, error: "Request too large" })}\n`);
        return;
      }
      const nl = buf.indexOf("\n");
      if (nl < 0) return;
      const line = buf.slice(0, nl);
      const rest = buf.slice(nl + 1);
      buf = "";
      let req: IpcRequest;
      try {
        req = JSON.parse(line) as IpcRequest;
      } catch {
        socket.end(`${JSON.stringify({ ok: false, error: "Bad request" })}\n`);
        return;
      }
      if (req.kind === "session") {
        socket.off("data", onData);
        this.session(socket, req, rest);
        return;
      }
      void this.handle(req).then((reply) => {
        if (reply.ok === false && !reply.idle) this.opts.log?.(`mcp ${String(req.tool)} refused: ${reply.error}`);
        socket.end(`${JSON.stringify(reply)}\n`);
      });
    };
    socket.on("data", onData);
  }

  /** A delegated CLI's relay: from here on the connection is MCP, served in this process, as the agent. */
  private session(socket: Socket, req: IpcRequest, rest: string) {
    const info = typeof req.taskId === "string" ? this.opts.task(req.taskId) : null;
    if (!info?.delegated || typeof req.token !== "string" || !sameToken(info.token, req.token)) {
      socket.end(`${JSON.stringify({ ok: false, error: "Not allowed: this task has no agentes tools." })}\n`);
      return;
    }
    const { delegated } = info;
    this.sessions.add(socket);
    socket.once("close", () => this.sessions.delete(socket));
    const input = new PassThrough({ encoding: "utf8" });
    input.write(rest);
    socket.pipe(input);
    void runMcpServer({
      taskId: req.taskId,
      socketPath: this.socketPath,
      token: req.token,
      input,
      output: socket,
      ipc: (r) => this.handle(r),
      scope: delegated.scope,
      profile: delegated.profile,
      context: {
        ...(delegated.branches ? { branches: delegated.branches } : {}),
        ...(delegated.asks ? { asks: delegated.asks } : {}),
        ...(delegated.task ? { task: true } : {}),
        ...(delegated.local ? { local: true } : {}),
        delegated,
      },
    }).finally(() => socket.end());
  }

  async close() {
    this.detach();
    for (const [callId, p] of this.pending) {
      clearTimeout(p.timer);
      p.resolve(
        p.cut && !RESEND_SAFE.has(p.tool)
          ? { ok: false, error: MCP_CUT_OFF }
          : { ok: false, error: "The runner is stopping. Try again in a minute.", transient: true },
      );
      this.pending.delete(callId);
    }
    this.waiting.clear();
    const server = this.server;
    this.server = null;
    await this.closeRelays();
    if (server) await new Promise<void>((resolve) => server.close(() => resolve()));
    if (process.platform !== "win32") rmSync(this.opts.socketPath, { force: true });
  }
}

/** The MCP process's half: one request over the local endpoint. */
export function ipcCall(socketPath: string, req: IpcRequest, timeoutMs = MCP_CALL_TIMEOUT_MS + 30_000) {
  return new Promise<IpcReply>((resolve) => {
    let buf = "";
    let done = false;
    const finish = (r: IpcReply) => {
      if (done) return;
      done = true;
      clearTimeout(timer);
      socket.destroy();
      resolve(r);
    };
    const socket = createConnection(socketPath);
    const timer = setTimeout(() => finish({ ok: false, error: "The runner did not answer in time." }), timeoutMs);
    socket.setEncoding("utf8");
    socket.on("connect", () => socket.write(`${JSON.stringify(req)}\n`));
    socket.on("data", (chunk: string) => {
      buf += chunk;
      const nl = buf.indexOf("\n");
      if (nl < 0) return;
      try {
        finish(JSON.parse(buf.slice(0, nl)) as IpcReply);
      } catch {
        finish({ ok: false, error: "The runner answered something unexpected." });
      }
    });
    socket.on("error", () =>
      finish({
        ok: false,
        error: "The agentes runner is not running on this computer (start it: agentes-runner start).",
        transient: true,
      }),
    );
    socket.on("close", () => finish({ ok: false, error: "The runner closed the connection.", transient: true }));
  });
}

