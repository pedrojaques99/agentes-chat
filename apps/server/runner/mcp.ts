/**
 * The `--settings` file of a Claude Code turn or task (protocol 7): what it
 * may run without asking (anything else reaches our prompt tool).
 * `plan`: read only: our tools, reading files, the web (`WebSearch`,
 * `WebFetch`) and read-only shell commands (`ls`, `cat`, `head`, `git status`,
 * also `git -C <path> …`; Claude Code checks each part of a pipeline). `work`: edits (`acceptEdits`), the same
 * read-only commands, plain file work, git work, pull requests, tests and
 * builds. Merges, deploys and publishing are denied (deny rules win over
 * allow rules); every push is `ask` (`PUSH_ASK_RULES`, which outranks allow
 * rules), so the prompt tool reads where it goes.
 */
export function claudePermissionSettings(
  mode: "plan" | "work" | "chat",
  missionAllow: string[] = [],
  /** An item's mission folder when it runs elsewhere (its worktree or subfolder). */
  missionFolder?: string,
  opts: {
    /**
     * Brain turns (ADR 0053 §3): shell reads aren't allow rules (`Bash(cat *)` would read a key); every
     * command reaches our prompt tool, where `localVerdict` allows plain reads at once and refuses secrets.
     */
    promptReads?: boolean;
    /** The runner's home when it isn't under `.agentes-runner` (system mode): read by no tool or command either. */
    runnerHome?: string;
    /**
     * The agent always asks (ADR 0173): a `work` turn allows only what reads, so every edit and every other command
     * reaches our prompt tool, and from there the server.
     */
    asksFirst?: boolean;
  } = {},
) {
  const shellReads = opts.promptReads ? [] : readOnlyShell();
  const home = opts.runnerHome?.startsWith("/") && !opts.runnerHome.includes("*") ? opts.runnerHome : null;
  const homeDeny = home ? [`Read(/${home}/**)`, `Bash(*${home}/*)`] : [];
  // The team's right hand on a person's plan (protocol 41): our tools only, every tool of Claude Code's own refused.
  if (mode === "chat") {
    return {
      permissions: { allow: ["mcp__agentes"], deny: [...CHAT_DENIED_TOOLS, ...ALWAYS_DENY_RULES, ...homeDeny] },
    };
  }
  if (mode === "plan") {
    return {
      permissions: {
        allow: [
          "mcp__agentes",
          "Read",
          "Glob",
          "Grep",
          "LS",
          "WebSearch",
          "WebFetch",
          ...shellReads,
          ...(opts.promptReads ? [] : gitC(GIT_READ.flatMap((c) => [`Bash(git ${c})`, `Bash(git ${c} *)`]))),
          ...missionFolderRules(missionFolder, ["Read"]),
        ],
        ask: [...PUSH_ASK_RULES],
        deny: [...PLAN_DENY, ...ALWAYS_DENY_RULES, ...homeDeny],
      },
    };
  }
  if (opts.asksFirst) {
    return {
      permissions: {
        allow: ["mcp__agentes", ...shellReads, ...missionFolderRules(missionFolder, ["Read"])],
        ask: [...PUSH_ASK_RULES],
        deny: [...ALWAYS_DENY_RULES, ...homeDeny],
      },
    };
  }
  return {
    permissions: {
      allow: [
        "mcp__agentes",
        ...shellReads,
        ...FILE_WORK.map((c) => `Bash(${c} *)`),
        ...gitC(GIT_WORK.flatMap((c) => [`Bash(git ${c})`, `Bash(git ${c} *)`])),
        "Bash(gh pr create *)",
        "Bash(gh pr view *)",
        "Bash(gh pr list *)",
        "Bash(gh pr checks *)",
        "Bash(gh pr diff *)",
        "Bash(gh pr status *)",
        ...BUILD_RULES,
        // The mission folder, for an item working in its own worktree or subfolder.
        ...missionFolderRules(missionFolder, ["Read", "Edit", "Write"]),
        // What a person allowed for the whole mission ("Aprovar sempre nesta missão").
        ...missionAllow.filter(isSafeRule).slice(0, 100),
      ],
      ask: [...PUSH_ASK_RULES],
      deny: [...ALWAYS_DENY_RULES, ...homeDeny],
    },
  };
}

